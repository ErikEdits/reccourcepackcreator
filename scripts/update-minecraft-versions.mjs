// Regenerates src/shared/minecraft-versions.data.ts.
//
// Releases from 1.14 on come from misode/mcmeta, which extracts the resource
// pack format of every version from Mojang's client JARs. Older releases are
// not covered there and are listed below by hand.
//
// Usage: node scripts/update-minecraft-versions.mjs

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const SOURCE = 'https://raw.githubusercontent.com/misode/mcmeta/summary/versions/data.json'
const OUTPUT = fileURLToPath(new URL('../src/shared/minecraft-versions.data.ts', import.meta.url))

/** [version, pack format] for releases before 1.14, oldest first. */
const OLD_RELEASES = [
  ...['1.6.1', '1.6.2', '1.6.4'].map((id) => [id, 1]),
  ...['1.7.2', '1.7.4', '1.7.5', '1.7.6', '1.7.7', '1.7.8', '1.7.9', '1.7.10'].map((id) => [id, 1]),
  ...['1.8', '1.8.1', '1.8.2', '1.8.3', '1.8.4', '1.8.5', '1.8.6', '1.8.7', '1.8.8', '1.8.9'].map(
    (id) => [id, 1],
  ),
  ...['1.9', '1.9.1', '1.9.2', '1.9.3', '1.9.4', '1.10', '1.10.1', '1.10.2'].map((id) => [id, 2]),
  ...['1.11', '1.11.1', '1.11.2', '1.12', '1.12.1', '1.12.2'].map((id) => [id, 3]),
  ...['1.13', '1.13.1', '1.13.2'].map((id) => [id, 4]),
]

const response = await fetch(SOURCE)
if (!response.ok) throw new Error(`${SOURCE}: HTTP ${response.status}`)
const versions = await response.json()

const recent = versions
  .filter((version) => version.type === 'release')
  .sort((a, b) => a.release_time.localeCompare(b.release_time))
  .map((version) => [
    version.id,
    version.resource_pack_version,
    version.resource_pack_version_minor ?? 0,
  ])

const known = new Set(OLD_RELEASES.map(([id]) => id))
const rows = [
  ...OLD_RELEASES.map(([id, major]) => [id, major, 0]),
  ...recent.filter(([id]) => !known.has(id)),
]

const lines = rows.map(([id, major, minor]) => `  ['${id}', ${major}, ${minor}],`)
writeFileSync(
  OUTPUT,
  `// Generated by scripts/update-minecraft-versions.mjs — do not edit by hand.
// [release, resource pack format major, minor], oldest first.

export const RELEASES: readonly (readonly [string, number, number])[] = [
${lines.join('\n')}
]
`,
)
console.log(`Wrote ${rows.length} releases (latest: ${rows.at(-1)[0]}) to ${OUTPUT}`)
